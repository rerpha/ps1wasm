// Screenshots of the UI states for visual review.
import { chromium } from 'playwright-core';
import http from 'node:http'; import fs from 'node:fs'; import path from 'node:path'; import os from 'node:os';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const dist = path.join(here, '../../dist'), assets = path.join(here, 'assets'), out = process.argv[2] ?? '/tmp';
const types = { '.html': 'text/html', '.js': 'text/javascript', '.wasm': 'application/wasm' };
const server = http.createServer((req, res) => { const p = path.join(dist, req.url === '/' ? 'index.html' : req.url.split('?')[0]);
  fs.readFile(p, (e, d) => { if (e) { res.writeHead(404); res.end(); return; } res.writeHead(200, { 'Content-Type': types[path.extname(p)] ?? 'application/octet-stream' }); res.end(d); }); }).listen(0);
const chromeDir = path.join(os.homedir(), '.cache/ms-playwright');
const exe = fs.readdirSync(chromeDir).filter(d => d.startsWith('chromium-')).map(d => path.join(chromeDir, d, 'chrome-linux64/chrome')).find(fs.existsSync);
const b = await chromium.launch({ executablePath: exe }); const page = await b.newPage({ viewport: { width: 1100, height: 900 } });
await page.goto(`http://localhost:${server.address().port}/`); await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/ui-1-start.png` });
await page.setInputFiles('#bios-input', path.join(assets, 'openbios.bin')); await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/ui-2-bios.png` });
await page.setInputFiles('#game-input', [path.join(assets, 'demo.cue'), path.join(assets, 'demo.bin')]);
await page.waitForTimeout(9000); await page.screenshot({ path: `${out}/ui-3-running.png` });
await page.click('#btn-settings'); await page.waitForTimeout(400); await page.screenshot({ path: `${out}/ui-4-settings.png` });
await b.close(); server.close();
